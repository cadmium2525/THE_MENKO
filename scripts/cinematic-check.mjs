import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(process.env.PLAYWRIGHT_PACKAGE_JSON||import.meta.url);
const{chromium}=require('playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await mkdir('test-results',{recursive:true});
const click=async a=>{await page.locator(`[data-action="${a}"]`).first().click();await page.waitForTimeout(280);};
await page.addInitScript(()=>{const original=crypto.getRandomValues.bind(crypto);crypto.getRandomValues=a=>{if(a instanceof Uint32Array&&a.length===1){a[0]=3;return a;}return original(a);};});
await page.goto(process.env.MENKO_TEST_URL||pathToFileURL(path.resolve('THE-MENKO.html')).href);
await click('quick');await click('musou');
await page.waitForTimeout(300);
const b=await page.locator('#arena').boundingBox();
await page.touchscreen.tap(b.x+b.width*.5,b.y+b.height*.55);
await page.waitForTimeout(260);await page.screenshot({path:'test-results/cinema-01-descent.png'});
await page.waitForTimeout(1000);await page.screenshot({path:'test-results/cinema-02-impact.png'});
assert.ok(await page.locator('#arena-wrap.cinematic').count());
await page.waitForTimeout(300);assert.ok(await page.locator('#impact-score').isVisible());
assert.match(await page.locator('#impact-score').textContent(),/\d+.*枚!!/);
await click('skip');await click('rematch');
await click('settings');await page.locator('#setting-reduced').check();await click('close-dialog');
await page.touchscreen.tap(b.x+b.width*.5,b.y+b.height*.55);await page.waitForTimeout(250);
assert.equal(await page.locator('#arena-wrap.cinematic').count(),0);
await page.screenshot({path:'test-results/cinema-03-reduced.png'});
await click('skip');
await writeFile('test-results/cinema-report.json',JSON.stringify({errors,cinematic:true,reducedMotion:true},null,2));
console.log(JSON.stringify({errors,cinematic:true,reducedMotion:true}));
await browser.close();assert.equal(errors.length,0);
